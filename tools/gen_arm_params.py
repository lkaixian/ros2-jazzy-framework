#!/usr/bin/env python3
"""One page with every arm setting: docs/arm-parameters.md.

    python3 tools/gen_arm_params.py             # from the files as they are now (your local edits included), for reading
    python3 tools/gen_arm_params.py --from-head # from the last commit, for the committed copy

The settings live in several files (ROS parameter files, calibration files, constants in the code). This page copies the real text, comments
included, and lists the code constants with their file and line. It is a VIEW: change a value in the file named above it, then regenerate.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PARAM = 'src/framework_bringup/param'
HEAD = '--from-head' in sys.argv

# (file, names): module-level constants that matter to the arm and live in code, not in a parameter file
CODE = [
    ('src/arm_control/arm_control/motion.py', ['RATE', 'MIN_LEG_SEC']),
    ('src/arm_control/arm_control/gripper.py',
     ['M_PER_TICK', 'M_OFFSET', 'CLOSED_TICKS', 'OPEN_TICKS', 'GAP_CLOSED_MM', 'GAP_OPEN_MM', 'SAFE_OPEN', 'SAFE_CLOSE']),
    ('src/arm_control/arm_control/track.py', ['CHI_GATE', 'GATE_FLOOR_M']),
    ('src/arm_control/arm_control/hand_eye.py', ['R_G_C']),
    ('tools/arm/gripper_tool.py', ['CURRENT_CAP', 'STEP', 'TICK', 'STALL_SEC', 'MOVE_LIMIT_SEC', 'V_MIN', 'TEMP_MAX']),
    ('tools/arm/arm_tool.py', ['RATE', 'MIN_SEC', 'TOL', 'TRACK_ERR', 'TRACK_SEC']),
]


def read(rel):
    if HEAD:
        r = subprocess.run(['git', 'show', f'HEAD:{rel}'], cwd=ROOT, capture_output=True, text=True)
        return r.stdout if r.returncode == 0 else None
    p = os.path.join(ROOT, rel)
    return open(p).read() if os.path.exists(p) else None


def block(text, key):
    """The top-level YAML section `key:` up to the next top-level key, comments included."""
    out, on = [], False
    for line in text.splitlines():
        top = bool(line) and not line[0].isspace() and not line.startswith('#')
        if top and re.match(rf'{re.escape(key)}:', line):
            on = True
        elif top and on:
            break
        if on:
            out.append(line)
    return '\n'.join(out).rstrip()


def fenced(body, lang='yaml'):
    return f'```{lang}\n{body}\n```\n\n'


def constants(rel, names):
    """Table rows for module-level `NAME = value` and `A, B = v1, v2` assignments of the wanted names."""
    text = read(rel)
    if text is None:
        return []
    rows = []
    for i, line in enumerate(text.splitlines(), 1):
        m = re.match(r'([A-Z][A-Z0-9_]*(?:\s*,\s*[A-Z][A-Z0-9_]*)*)\s*=\s*(.+)$', line)
        if not m:
            continue
        keys = [k.strip() for k in m.group(1).split(',')]
        vals = [v.strip() for v in m.group(2).split('#')[0].split(',')] if len(keys) > 1 else [m.group(2).split('#')[0].strip()]
        for k, v in zip(keys, vals):
            if k in names:
                rows.append(f'| `{k}` | `{v}` | `{rel}:{i}` |')
    return rows


def page():
    t = ('# Arm parameters, all in one place\n\n'
         'Generated by `tools/gen_arm_params.py` from the real files (comments included). It is a **view**: edit the value in the file named '
         'above each block, then regenerate. Parameter files under `src/framework_bringup/param/` are read from the installed copy, so after '
         'editing run `colcon build --packages-select framework_bringup` and restart the node (`pkill -f "[a]rm_extension_node"`; the launch '
         'respawns it). A few can be changed live with `ros2 param set /arm_extension_node <name> <value>` (it resets when the node restarts).\n\n')
    ext = read(f'{PARAM}/extensions.yaml') or ''
    t += ('## 1. Pick, motion and the safety gates: `extensions.yaml` > `arm_extension_node`\n\n'
          'Includes `live` (the master switch: false = plans only, prints `DRY:`), `rate` (arm speed), `workspace_min/max`, the finger pitch and '
          'stand-off, the tracker (`track_*`), the camera source (`target_source`, `fixed_cam_xyz`), the gripper limits and `object_width_mm`.\n\n')
    t += fenced(block(ext, 'arm_extension_node'))
    t += '## 2. Servo health gate: `extensions.yaml` > `arm_health_node`\n\n' + fenced(block(ext, 'arm_health_node'))
    for title, rel, why in [
            ('3. Camera on the gripper (OAK): `oak.yaml`', f'{PARAM}/oak.yaml', 'Where the OAK sits on the gripper and its streams.'),
            ('4. Hand-eye calibration: `arm_hand_eye.yaml`', f'{PARAM}/arm_hand_eye.yaml',
             'Camera pose on the gripper and intrinsics; `verified: false` until a touch test.'),
            ('5. Camera fixed to the base (RealSense): `realsense.yaml`', f'{PARAM}/realsense.yaml',
             'Resolution and alignment of the colour and depth the base-camera pick reads.'),
            ('6. Gripper calibration: `arm_gripper.yaml`', f'{PARAM}/arm_gripper.yaml',
             'Open and closed positions (the repo copy; your measured copy is `~/arm_gripper.yaml`).'),
            ('7. Rest pose: `arm_rest_pose.yaml`', f'{PARAM}/arm_rest_pose.yaml', 'The folded pose the arm parks to.')]:
        body = read(rel)
        if body is not None:
            t += f'## {title}\n\n{why}\n\n' + fenced(body.rstrip())
    per = read(f'{PARAM}/perception.yaml')
    if per:
        t += ('## 8. The object detector the pick reads: `perception.yaml` > `object_detection_node`\n\n'
              'Its `conf` is the confidence below which a box is not reported (a bottle too close or cut off can fall under it). The image topic is in '
              '`models/local.yaml` (not in git).\n\n' + fenced(block(per, 'object_detection_node')))
    local = read('models/local.yaml')
    if local:
        t += '### `models/local.yaml` (this machine only)\n\n' + fenced(local.rstrip())
    t += ('## 9. Settings that live in the code, not in a file\n\n'
          'Change these by editing the source (and rebuilding), so treat them as fixed unless you know why. File and line shown.\n\n'
          '| name | value | where |\n|---|---|---|\n')
    for rel, names in CODE:
        t += '\n'.join(constants(rel, names)) + '\n' if constants(rel, names) else ''
    t += '\n'
    marks = []
    for rel in sorted([f'{PARAM}/extensions.yaml', f'{PARAM}/oak.yaml', f'{PARAM}/arm_hand_eye.yaml', f'{PARAM}/realsense.yaml']):
        for i, line in enumerate((read(rel) or '').splitlines(), 1):
            if 'LOCAL TEST' in line:
                marks.append(f'- `{rel}:{i}`  {line.strip()[:150]}')
    t += '## 10. Temporary local test settings (do not commit)\n\n' + ('\n'.join(marks) if marks else 'None: every value above is the committed one.') + '\n'
    return t


if __name__ == '__main__':
    out = os.path.join(ROOT, 'docs', 'arm-parameters.md')
    open(out, 'w').write(page())
    print('wrote', out, '(from', 'the last commit' if HEAD else 'the working tree', ')')
