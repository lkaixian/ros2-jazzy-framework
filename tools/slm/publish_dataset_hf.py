#!/usr/bin/env python3
"""Upload the synthetic training data to the Hugging Face Hub as a dataset (private unless --public).

  python3 tools/slm/publish_dataset_hf.py --repo <you>/<dataset-name> --data-dir bt_dataset_v3 --public
Publishes two configs: `slm` (task spec -> BehaviorTree.CPP XML rows from `make_bt_dataset`, train + validation) and `commands`
(GPSR-style spoken commands with a gold plan and what a correct plan must contain, from tools/gpsr/commands.py). Nested plan fields are
stored as JSON strings so the Hub's dataset viewer can load them. The card is neutral: no project name, paths or links.
"""
import argparse
import json
import os
import shutil
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
CARD = """---
license: apache-2.0
language: [en]
task_categories: [text-generation]
tags: [synthetic, behavior-trees, robotics, instruction-following]
size_categories: [10K<n<100K]
configs:
- config_name: slm
  data_files:
  - {{split: train, path: slm/train.jsonl}}
  - {{split: validation, path: slm/val.jsonl}}
- config_name: commands
  data_files:
  - {{split: train, path: commands/gpsr_style.jsonl}}
---
# {title}

Synthetic data for turning spoken-style robot commands into behaviour trees. Everything here is generated by code: no real people, recordings or
personal data.

## Config `slm`: task spec -> BehaviorTree.CPP v4 XML ({n_train:,} train / {n_val} validation rows)
Fields: `prompt`, `completion`, `kind`.
- `prompt` = `### NODES` (a random subset of the node catalog, one line per node: `Name[Category](required,optional?)`), `### TASK_SPEC` (a JSON spec: goal,
  steps, nested `Sequence`/`Fallback`/`ReactiveSequence`/`ReactiveFallback`/`Parallel` groups, `retry`, `repeat`, `success_count`), and for repair rows
  `### PREVIOUS_XML` and `### ERRORS` (validator messages).
- `completion` = the BehaviorTree.CPP v4 XML for that spec. Labels come from a rule-based generator and are **checked by a validator** (unknown nodes,
  missing ports, cycles, limits), so every completion is a valid tree.
- `kind` = `generate` ({n_gen:,} rows) or `repair` ({n_rep:,} rows: fix a previous attempt using the validator errors).
- Catalog: 45 nodes (navigation, perception conditions, speech, arm and gripper placeholders, loops/decorators).
- A 230M model fine-tuned on the first 6,000 train rows (2,835 of them under 768 tokens) reaches valid 0.995 / exact 0.935 on 200 held-out rows
  (against the rule-based generator, synthetic specs only).

## Config `commands`: GPSR-style commands with a gold plan ({n_cmd:,} rows)
Fields: `id`, `category` (navigation, people, vision, refuse), `command`, `expect` (JSON string: what a correct plan must contain, e.g. rooms visited in
order, a spoken line, a macro, a node, a refusal), `gold` (JSON string: one correct task spec using named macros). Manipulation requests
("bring me a cup") are labelled as refusals because the target robot has no working arm. Templates are original, in the style of household-robot
command tests; they are not any competition's official sentences.

## Limitations
Synthetic and template-based: a model trained on it learns the grammar and the catalog, not natural language variety. Held-out scores on `slm` are against
the generator that made the labels. The node catalog and place names (`door`, `left_room`, ...) are specific to one robot setup.

License: Apache-2.0.
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--repo', required=True)
    ap.add_argument('--data-dir', default='bt_dataset_v3')
    ap.add_argument('--commands', type=int, default=1000)
    ap.add_argument('--public', action='store_true')
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()
    from huggingface_hub import HfApi, get_token
    if not a.dry_run and not get_token():
        sys.exit('no Hugging Face login: run `hf auth login` first')
    sys.path.insert(0, HERE + '/../gpsr')
    import commands
    with tempfile.TemporaryDirectory() as tmp:
        for d in ('slm', 'commands'):
            os.makedirs(os.path.join(tmp, d))
        kinds = {}
        n = {}
        for name, dst in (('train', 'train'), ('val', 'val')):
            src = os.path.join(a.data_dir, name + '.jsonl')
            shutil.copy(src, os.path.join(tmp, 'slm', dst + '.jsonl'))
            rows = [json.loads(line) for line in open(src)]
            n[name] = len(rows)
            if name == 'train':
                for r in rows:
                    kinds[r['kind']] = kinds.get(r['kind'], 0) + 1
        items = commands.generate(a.commands, seed=1)
        with open(os.path.join(tmp, 'commands', 'gpsr_style.jsonl'), 'w') as f:
            for it in items:
                f.write(json.dumps({'id': it['id'], 'category': it['category'], 'command': it['command'],
                                    'expect': json.dumps(it['expect']), 'gold': json.dumps(it['gold'])}) + '\n')
        card = CARD.format(title=a.repo.split('/')[-1], n_train=n['train'], n_val=n['val'], n_gen=kinds.get('generate', 0),
                           n_rep=kinds.get('repair', 0), n_cmd=len(items))
        open(os.path.join(tmp, 'README.md'), 'w').write(card)
        print(f"{'would upload' if a.dry_run else 'uploading'} dataset to {a.repo} "
              f"(new repos: {'public' if a.public else 'private'}; an existing repo keeps its visibility): {sorted(os.listdir(tmp))}")
        if a.dry_run:
            return
        api = HfApi()
        api.create_repo(a.repo, repo_type='dataset', private=not a.public, exist_ok=True)
        api.upload_folder(folder_path=tmp, repo_id=a.repo, repo_type='dataset', commit_message='Synthetic behaviour-tree data')
    print(f'done: https://huggingface.co/datasets/{a.repo}')


if __name__ == '__main__':
    main()
