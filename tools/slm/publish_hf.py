#!/usr/bin/env python3
"""Upload the fine-tuned SLM to the Hugging Face Hub (private unless you pass --public).

  hf auth login                                  # once, in your own terminal (the token never goes through this script's arguments)
  python3 tools/slm/publish_hf.py --model models/bt-slm --repo <your-user>/robocup-bt-slm --valid 0.975 --exact 0.915
  python3 tools/slm/publish_hf.py ... --public   # only when you want it visible to everyone

Writes a model card and copies the base model's LFM Open License v1.0 (required by section 4 of that licence: give recipients a copy,
say the files were changed, keep the attribution). Commercial use above 10 M USD annual revenue is restricted by that licence.
Nothing is uploaded without a valid login; `--dry-run` only prints what would be uploaded.
"""
import argparse
import os
import shutil
import sys
import tempfile
import urllib.request

BASE = 'LiquidAI/LFM2.5-230M-Base'
CARD = """---
license: other
license_name: lfm1.0
license_link: LICENSE
base_model: {base}
tags: [robotics, behavior-trees, robocup, fine-tuned]
---
# robocup-bt-slm: task spec -> BehaviorTree.CPP XML

A small causal LM fine-tuned from [{base}](https://huggingface.co/{base}) (**modified: fine-tuned, files changed**) to turn a JSON task spec
(plus the node catalog, previous XML and validator errors on a retry) into BehaviorTree.CPP v4 XML. It is the "fast brain" of
https://github.com/lkaixian/ros2-jazzy-framework (`bt_slm`); an exact rule-based generator is tried first and this model only handles retries.

- Training data: synthetic (task spec, XML) pairs generated by `make_bt_dataset` and labelled by the real validator; rows longer than {max_len} tokens
  were skipped; 1 epoch, batch size 1, GTX 1650.
- Held-out score against the rule-based generator on synthetic specs: valid {valid}, exact {exact}. This shows the model learned the rules; it
  is NOT evaluated on real LLM output.
- Use: set `bt_slm_node.model_path` or `ROBOCUP_SLM_MODEL`, or put the files in the repo's `models/bt-slm/`.
- License: the base model's LFM Open License v1.0 (copy in `LICENSE`); attribution to Liquid AI, Inc. retained; commercial use is restricted above the
  license's revenue threshold.
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--model', default='models/bt-slm')
    ap.add_argument('--repo', required=True, help='<user-or-org>/<name>')
    ap.add_argument('--valid', default='n/a')
    ap.add_argument('--exact', default='n/a')
    ap.add_argument('--max-len', default='768')
    ap.add_argument('--public', action='store_true')
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()
    if not os.path.exists(os.path.join(a.model, 'model.safetensors')):
        sys.exit(f'{a.model}/model.safetensors not found')
    from huggingface_hub import HfApi, get_token
    if not a.dry_run and not get_token():
        sys.exit('no Hugging Face login: run `hf auth login` in your terminal first')
    with tempfile.TemporaryDirectory() as tmp:
        stage = os.path.join(tmp, 'stage')
        shutil.copytree(a.model, stage)
        with urllib.request.urlopen(f'https://huggingface.co/{BASE}/raw/main/LICENSE', timeout=30) as r:
            open(os.path.join(stage, 'LICENSE'), 'wb').write(r.read())
        open(os.path.join(stage, 'README.md'), 'w').write(CARD.format(base=BASE, valid=a.valid, exact=a.exact, max_len=a.max_len))
        files = sorted(os.listdir(stage))
        print(f"{'would upload' if a.dry_run else 'uploading'} to {a.repo} ({'public' if a.public else 'private'}): {files}")
        if a.dry_run:
            return
        api = HfApi()
        api.create_repo(a.repo, private=not a.public, exist_ok=True)
        api.upload_folder(folder_path=stage, repo_id=a.repo, commit_message='Fine-tuned bt-slm weights')
    print(f'done: https://huggingface.co/{a.repo}')


if __name__ == '__main__':
    main()
