#!/usr/bin/env python3
"""Generate the reference pages that must never drift: docs/node-catalog.md, docs/parameters.md, docs/messages.md.
Run with the workspace sourced (env.sh): python3 tools/gen_reference_docs.py"""
import glob
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PARAM = os.path.join(ROOT, 'src/framework_bringup/param')


def node_catalog():
    out = subprocess.run(['ros2', 'run', 'bt_validator', 'validate_bt', '--list-nodes'], capture_output=True, text=True, check=True).stdout
    rows, cur = {}, None
    for ln in out.splitlines():
        if ln[:1].strip():
            cat, name, rest = ln.split(None, 2)
            cur = (cat, name, rest.replace('ports:', '').strip())
            rows.setdefault(cat, []).append([name, cur[2], ''])
        elif ln.strip() and cur:
            rows[cur[0]][-1][2] = ln.strip()
    t = ('# BT node catalog\n\nGenerated by `tools/gen_reference_docs.py` from the live catalog '
         '(`ros2 run bt_validator validate_bt --list-nodes`): '
         'core BehaviorTree.CPP nodes plus every extension manifest. `?` marks an optional port. Port values are strings; a blackboard '
         'reference is `{name}`; `out_*` ports write the node\'s result to the blackboard. '
         '`name` and `ID` are reserved by BehaviorTree.CPP.\n\n')
    for cat in ('Action', 'Condition', 'Control', 'Decorator'):
        t += f'## {cat}s\n\n| Node | Ports | What it does |\n|---|---|---|\n'
        for n, p, d in rows.get(cat, []):
            t += f'| `{n}` | {p.replace("?", "?") if p != "-" else "none"} | {d or ""} |\n'
        t += '\n'
    open(os.path.join(ROOT, 'docs/node-catalog.md'), 'w').write(t)


def parameters():
    t = ('# Parameter files\n\nGenerated by `tools/gen_reference_docs.py`: the real files in '
         '`src/framework_bringup/param/`, comments included. '
         'Precedence: package defaults < these files < launch arguments you actually pass. Edit and relaunch (no rebuild). '
         '`ros2 run framework_bringup check_params` starts every node with these files and reports unknown or mistyped keys.\n\n')
    for f in ('pipeline', 'perception', 'extensions', 'audio', 'llama_server', 'navigation', 'nav_sim', 'cluster', 'places'):
        p = os.path.join(PARAM, f + '.yaml')
        if os.path.exists(p):
            t += f'## `{f}.yaml`\n\n```yaml\n{open(p).read().rstrip()}\n```\n\n'
    open(os.path.join(ROOT, 'docs/parameters.md'), 'w').write(t)


def messages():
    t = ('# Message, service and action definitions\n\nGenerated by `tools/gen_reference_docs.py` '
         'from the `.msg`, `.srv` and `.action` files.\n\n')
    for pkg in ('bt_pipeline_msgs', 'object_detection_msgr', 'person_detection_msgr', 'face_recognition_msgr', 'audio_msgr',
                'cluster_msgs'):
        files = sorted(glob.glob(f'{ROOT}/src/{pkg}/msg/*.msg') + glob.glob(f'{ROOT}/src/{pkg}/srv/*.srv')
                       + glob.glob(f'{ROOT}/src/{pkg}/action/*.action'))
        if not files:
            continue
        t += f'## `{pkg}`\n\n'
        for f in files:
            kind = os.path.basename(os.path.dirname(f))
            t += f'### {os.path.basename(f)[:-len(os.path.splitext(f)[1])]} ({kind})\n\n```\n{open(f).read().rstrip()}\n```\n\n'
    open(os.path.join(ROOT, 'docs/messages.md'), 'w').write(t)


if __name__ == '__main__':
    node_catalog()
    parameters()
    messages()
